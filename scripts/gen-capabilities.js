#!/usr/bin/env node
// Generates Sources/Capabilities/CapabilityMatrix.generated.swift from Resources/capability-matrix.json.
// The JSON is Morph's capability plan from docs/spec §3 (275 conversion paths, 26 tools, 6 actions).
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const m = JSON.parse(fs.readFileSync(path.join(root, "Resources/capability-matrix.json"), "utf8"));

const ACTION_DESCRIPTIONS = {
  airDrop: "Send to a nearby Apple device using the system AirDrop sheet.",
  float: "Park items on a small always-on-top tray, then drag them out later.",
  copy: "Put the items on the clipboard so you can paste them in Finder.",
  move: "Pick a folder and relocate the original items to it.",
  copyPath: "Put each item’s full path on the clipboard, one per line.",
  openTerminal: "Start a Terminal session in the item’s folder (or the folder itself).",
};

const q = (s) => JSON.stringify(s);
const arr = (a) => `[${a.map(q).join(", ")}]`;
let total = 0;
const inputs = Object.keys(m.conversions);
const convLines = inputs.map((k) => { total += m.conversions[k].length; return `        ${q(k)}: ${arr(m.conversions[k])},`; });
if (total !== 275) throw new Error(`expected 275 conversion paths, got ${total}`);
const toolIds = Object.keys(m.toolDefs);
if (toolIds.length !== 26) throw new Error(`expected 26 tools, got ${toolIds.length}`);
const actionIds = Object.keys(m.actionDefs);
if (actionIds.length !== 6) throw new Error(`expected 6 actions, got ${actionIds.length}`);

const out = `// GENERATED by scripts/gen-capabilities.js from Resources/capability-matrix.json. Do not edit.
// Source of the matrix: docs/spec/README.md §3.1 (275 conversion paths · 26 tools · 6 actions).

public enum CapabilityMatrix {
    /// Input format → conversion targets (source format never included). ${inputs.length} inputs, ${total} paths.
    public static let conversions: [String: [String]] = [
${convLines.join("\n")}
    ]

    /// Input order as published (used for stable iteration in tests and reports).
    public static let inputOrder: [String] = ${arr(inputs)}

    /// Input format → (single-file tools, multi-file tools), in wheel order.
    public static let tools: [String: (single: [String], multi: [String])] = [
${Object.entries(m.tools).map(([k, v]) => `        ${q(k)}: (single: ${arr(v.single)}, multi: ${arr(v.multi)}),`).join("\n")}
    ]

    /// Tool id → (wheel title, display name). ${toolIds.length} tools.
    public static let toolDefs: [String: (title: String, name: String)] = [
${toolIds.map((k) => `        ${q(k)}: (title: ${q(m.toolDefs[k].title)}, name: ${q(m.toolDefs[k].name)}),`).join("\n")}
    ]

    /// Action ids in wheel order. ${actionIds.length} actions.
    public static let actionOrder: [String] = ${arr(actionIds)}

    /// Action id → (wheel title, display name, Morph description).
    public static let actionDefs: [String: (title: String, name: String, description: String)] = [
${actionIds.map((k) => `        ${q(k)}: (title: ${q(m.actionDefs[k].title)}, name: ${q(m.actionDefs[k].name)}, description: ${q(ACTION_DESCRIPTIONS[k])}),`).join("\n")}
    ]
}
`;
fs.writeFileSync(path.join(root, "Sources/Capabilities/CapabilityMatrix.generated.swift"), out);
console.log(`generated: ${inputs.length} inputs, ${total} conversion paths, ${toolIds.length} tools, ${actionIds.length} actions`);
