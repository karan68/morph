#!/usr/bin/env node
// Generates Sources/Engines/FFmpegRecipes.generated.swift from engine-recipes/ffmpeg-recipes.json,
// so the app and the Tokyo VM harness use identical FFmpeg command lines.
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const j = JSON.parse(fs.readFileSync(path.join(root, "engine-recipes/ffmpeg-recipes.json"), "utf8"));
const q = (s) => JSON.stringify(s);
const lines = Object.entries(j.recipes).map(([k, r]) =>
  `        ${q(k)}: FFmpegRecipe(args: [${r.args.map(q).join(", ")}], requiresVideoToolbox: ${(r.requires || []).includes("videotoolbox")}),`);
const out = `// GENERATED by scripts/gen-recipes.js from engine-recipes/ffmpeg-recipes.json. Do not edit.

public struct FFmpegRecipe {
    public let args: [String]
    public let requiresVideoToolbox: Bool

    /// Args with {placeholders} substituted.
    public func resolved(_ values: [String: String]) -> [String] {
        args.map { arg in values.reduce(arg) { $0.replacingOccurrences(of: $1.key, with: $1.value) } }
    }
}

public enum FFmpegRecipes {
    public static let all: [String: FFmpegRecipe] = [
${lines.join("\n")}
    ]
}
`;
fs.writeFileSync(path.join(root, "Sources/Engines/FFmpegRecipes.generated.swift"), out);
console.log(`generated ${lines.length} recipes`);
